def decode_year(info: int):
  """把 info 解码成 [(月序, 是否闰月, 天数), ...]（按时间顺序）。"""
  leap = info & 0xF
  months = []
  for m in range(1, 13):
    months.append((m, False, 30 if info & (0x10000 >> m) else 29))
    if m == leap:
      months.append((m, True, 30 if info & 0x10000 else 29))
  return months


def build_calendar() -> lunar_common.LunarCalendar:
  months = []
  for i, (info, spring) in enumerate(LUNAR_INFO):
    year = TABLE_FIRST_YEAR + i
    start = datetime.date.fromisoformat(f"{year}-{spring}")
    if months:  # 交叉校验：上一年最后一个月结束的次日应是今年正月初一
      prev = months[-1]
      expected = prev.start + datetime.timedelta(days=prev.days)
      if expected != start:
        raise ValueError(f"{year} 年正月初一应为 {expected}，表中为 {start}")
    for month, leap, days in decode_year(info):
      months.append(lunar_common.LunarMonth(year, month, leap, start, days))
      start += datetime.timedelta(days=days)
  return lunar_common.LunarCalendar(months)


